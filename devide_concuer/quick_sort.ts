// Quick Sort — тоже «разделяй и властвуй», но по-другому:
// merge sort вкладывает работу в СЛИЯНИЕ после рекурсии,
// quicksort вкладывает работу в РАЗБИЕНИЕ (partition) до рекурсии.
//
// Идея в двух словах:
// 1) Выбери опорный элемент (pivot) — например, последний элемент массива.
// 2) Раздели остальные элементы на две группы:
//    - меньше pivot
//    - больше pivot
//    (пока не думай про эффективность — просто раздели)
// 3) Рекурсивно отсортируй каждую группу тем же способом.
// 4) Собери результат: [...отсортированное меньше, pivot, ...отсортированное больше]
//
// У тебя уже есть черновая версия в файле
// "recursion /quick_sort.ts" — глянь на неё, но в этот раз
// попробуй написать заново и подумать над вопросами ниже,
// не подглядывая.
//
// Подсказки:
// - База рекурсии та же, что в merge sort: arr.length <= 1 — уже отсортирован.
// - Как выбрать pivot? Что будет, если всегда брать arr[arr.length - 1]
//   на УЖЕ отсортированном или обратно отсортированном массиве?
//   (подумай про худший случай O(n^2) и почему выбор pivot на это влияет)
// - Простой вариант разбиения — через filter (как в старом файле) —
//   создаёт новые массивы на каждом уровне рекурсии.
//   Более «классический» вариант — partition в стиле Lomuto/Hoare,
//   который работает in-place, свапая элементы внутри одного массива
//   и возвращая индекс, куда встал pivot. Попробуй сначала простой
//   вариант через filter, а если хочется — реализуй ещё и in-place.
// - Важный частный случай: как твой partition обрабатывает элементы,
//   РАВНЫЕ pivot? Если делить строго на < pivot и > pivot,
//   куда деваются дубликаты pivot? (это как раз обработано в
//   черновике через pivot в середине результата — но подумай,
//   что будет, если в массиве много одинаковых элементов)
//
// О чём подумать отдельно:
// - Средняя сложность по времени — O(n log n), но худший случай — O(n^2).
//   При каких входных данных и выборе pivot наступает худший случай?
// - Требуется ли дополнительная память? Сравни с merge sort —
//   какой из двух алгоритмов легче сделать по-настоящему in-place?
// - Стабильна ли сортировка в твоей реализации?

function quickSort(arr: number[]): number[] {
  if (arr.length <= 1) {
    return arr;
  }

  const pivot = arr[arr.length - 1];
  const left = arr.filter((el) => el < pivot);
  const right = arr.filter((el) => el > pivot);

  return [...quickSort(left), pivot, ...quickSort(right)];
}

console.log(quickSort([5, 3, 8, 4, 2, 7, 1, 10]));
