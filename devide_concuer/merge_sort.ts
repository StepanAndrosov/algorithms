// Merge Sort — «разделяй и властвуй»
//
// Идея в двух словах:
// 1) Разделяй: делишь массив пополам, пока не останутся куски длиной 0 или 1
//    (такой кусок уже отсортирован по определению — это база рекурсии).
// 2) Властвуй: рекурсивно сортируешь каждую половину тем же способом.
// 3) Слияние (merge): у тебя есть ДВЕ уже отсортированные половины —
//    их нужно слить в один отсортированный массив за один проход.
//
// Подсказки по merge():
// - Заведи два указателя, по одному на каждый массив (i = 0, j = 0).
// - На каждом шаге сравнивай left[i] и right[j], меньший элемент
//   отправляй в результат и двигай соответствующий указатель.
// - Когда один из массивов закончился — весь остаток другого
//   можно просто доклеить (он уже отсортирован).
// - Возвращай НОВЫЙ массив, не пытайся мутировать исходные half'ы —
//   так проще не запутаться в индексах.
//
// Подсказки по mergeSort():
// - База рекурсии: если arr.length <= 1 — массив уже отсортирован, верни его как есть.
// - Найди середину: const mid = Math.floor(arr.length / 2).
// - Раздели на arr.slice(0, mid) и arr.slice(mid) — и рекурсивно
//   вызови mergeSort на каждой половине.
// - Собери результат через merge(left, right).
//
// О чём подумать отдельно:
// - Какая сложность по времени? (подумай, сколько уровней рекурсии
//   и сколько работы на каждом уровне — O(n log n))
// - Какая сложность по памяти? (в отличие от quicksort «на месте»,
//   этот вариант с slice()/merge() создаёт новые массивы — сколько именно?)
// - Стабильна ли твоя сортировка? (при равенстве left[i] === right[j]
//   какой элемент должен пойти первым, чтобы порядок равных элементов
//   не менялся?)
// - Что будет с пустым массивом? С массивом из одного элемента?
//   С массивом, где все элементы одинаковые?

// mergeSort([5,3,8,4,2,7,1,10])
// ├─ mergeSort([5,3,8,4])
// │  ├─ mergeSort([5,3])
// │  │  ├─ mergeSort([5])   → [5]   (база)
// │  │  └─ mergeSort([3])   → [3]   (база)
// │  └─ mergeSort([8,4])
// │     ├─ mergeSort([8])   → [8]   (база)
// │     └─ mergeSort([4])   → [4]   (база)
// └─ mergeSort([2,7,1,10])
//    ├─ mergeSort([2,7])
//    │  ├─ mergeSort([2])   → [2]   (база)
//    │  └─ mergeSort([7])   → [7]   (база)
//    └─ mergeSort([1,10])
//       ├─ mergeSort([1])   → [1]   (база)
//       └─ mergeSort([10])  → [10]  (база)

function mergeSort(arr: number[]): number[] {
  // TODO
  if (arr.length <= 1) {
    return arr;
  }
  const mid = Math.floor(arr.length / 2);
  const left = mergeSort(arr.slice(0, mid));
  const right = mergeSort(arr.slice(mid));
  return merge(left, right);
}

// merge([5],[3])   → [3,5]
// merge([8],[4])   → [4,8]
// merge([3,5],[4,8])   → [3,4,5,8]      ← это mergeSort([5,3,8,4])

// merge([2],[7])   → [2,7]
// merge([1],[10])  → [1,10]
// merge([2,7],[1,10])  → [1,2,7,10]     ← это mergeSort([2,7,1,10])

// merge([3,4,5,8],[1,2,7,10]) → [1,2,3,4,5,7,8,10]   ← финальный результат

function merge(left: number[], right: number[]): number[] {
  // TODO
  let i = 0;
  let j = 0;
  const result: number[] = [];

  while (i < left.length && j < right.length) {
    if (left[i] <= right[j]) {
      result.push(left[i]);
      i++;
    } else {
      result.push(right[j]);
      j++;
    }
  }
  if (left.length > i) {
    result.push(...left.slice(i));
  }
  if (right.length > j) {
    result.push(...right.slice(j));
  }
  return result;
}

